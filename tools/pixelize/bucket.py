# The fish bucket on the pond's dock behind TaniBot (Fishing package 4; a metal pail since package 5,
# Ardian 2026-11-12):
# original pixel art from simple shapes (like tools/pixelize/catch_icons.py), with our own catch
# icons (Tilapia, Catfish, Carp, Gourami) turned head-up, at half size, sticking out of the bucket.
# Usage: python3 -I tools/pixelize/bucket.py > web/src/art/pond-bucket.ts
# Letters = PALETTE (web/src/sprites.tsx) + FISH_PALETTE (web/src/art/catch-grids.ts). Standard library only.
import sys, os
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from catch_icons import G, tilapia, catfish, carp, gourami


def head_up_half(rows):
    """Turn a fish (face left) head-up, then halve it (keep a pixel if any of its 2x2 block is set)."""
    h, w = len(rows), len(rows[0])
    turned = [''.join(rows[h - 1 - y][x] for y in range(h)) for x in range(w)]  # clockwise: head on top
    out = []
    for y in range(0, len(turned) - 1, 2):
        r = ''
        for x in range(0, len(turned[0]) - 1, 2):
            block = [turned[y][x], turned[y][x + 1], turned[y + 1][x], turned[y + 1][x + 1]]
            inner = [c for c in block if c not in '.k']
            r += inner[0] if inner else ('k' if 'k' in block else '.')
        out.append(r)
    return out


W, H = 26, 30
g = G(W, H)
# (rows() trims empty edges; the handle's top may reach row 0)
# fish first (behind the bucket's front)
fish = [(tilapia(), 4, 1), (catfish(), 9, 0), (carp(), 13, 2), (gourami(), 17, 1)]
for rows, x0, y0 in fish:
    for y, r in enumerate(head_up_half(rows)):
        for x, ch in enumerate(r):
            if ch != '.' and 0 <= x0 + x < W and 0 <= y0 + y < H:
                g.put(x0 + x, y0 + y, ch)
# the bucket (package 5: a galvanised METAL pail, not a wooden barrel): dark inside behind the fish,
# a grey zinc body that is wider at the top, a light stripe on the left, shade on the right, raised
# rings around it, a rolled rim
g.ellipse(13, 13.5, 11, 3, 'X')                          # inside (behind the fish's lower bodies)
for y in range(14, H - 1):
    half = 11.2 - (y - 14) * 0.22                        # tapers toward the bottom
    l, r = round(13 - half), round(13 + half)
    for x in range(l, r):
        f = (x - l) / max(1, r - l)
        g.put(x, y, 'w' if 0.12 < f < 0.2 else 'e' if f < 0.62 else 'E' if f > 0.86 else 't')
for ry in (19, 25):                                       # raised rings
    half = 11.2 - (ry - 14) * 0.22
    g.line(round(13 - half), ry, round(13 + half) - 1, ry, 'T')
g.ellipse(13, H - 2.2, 8.2, 1.6, 'E')                    # the bottom's curve
g.ellipse(13, 13.8, 11.4, 1.5, 'e')                      # rolled rim
g.line(3, 13, 23, 13, 'w', only_on='e')                   # rim highlight
g.outline()
# the wire handle: a thin arc over the fish, from the ears on both sides of the rim
for i in range(41):
    t = i / 40
    x = 1 + t * 24
    y = 13 - 12.5 * 4 * t * (1 - t)
    g.put(round(x), round(y), 'w' if 0.3 < t < 0.45 else 'e')
g.put(1, 13, 'T'); g.put(25, 13, 'T')                    # the ears
rows = g.rows()
print('// Generated by tools/pixelize/bucket.py: the metal fish bucket (zinc pail, wire handle) on the pond\'s dock (original pixel')
print('// art; the fish are our own catch icons, head-up, at half size). Letters = PALETTE + FISH_PALETTE.')
print('')
print('export const FISH_BUCKET: string[] = [')
for r in rows:
    print(f"  '{r}',")
print('];')

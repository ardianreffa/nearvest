# The fishing pond for upright phones (Ardian 2026-11-12, docs/PLAN-fishing.md section 15): Ardian's
# ChatGPT phone pictures (day / dusk / night, same layout; a NEW composition, not the 16:9 one).
# From the three pixelized pictures (480 x 853, the night one aligned to the day one) this writes:
#  - the swaying tree crown per time (the day picture's leaf shape, each picture's colours);
#  - the lake's water as a mask (for the waves);
#  - the ducks' water map (only water under a whole duck) in the phone scene's grid, as TypeScript.
# The phone scene's grid is the picture / 1.4 (343 x 609): things in this picture are about 1.4 times
# bigger than in the 16:9 one, so TaniBot, frogs, ducks and the rod keep the same size in grid px.
# Usage: python3 -I tools/pixelize/pond_phone.py <day.png> <dusk.png> <night.png> <out dir> <out .ts>
# Standard library only.
import sys, os
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from png import read_png, write_png

R = 1.4                      # picture px per scene grid px
TREE = (0, 86, 112, 206)     # the big tree's crown (picture px, inclusive)
CELL = 4                     # duck map cell (grid px), like the 16:9 pond
HALF_W, HALF_H = 11, 7       # half a duck plus a margin (grid px)

day, dusk, night, out, out_ts = sys.argv[1:6]
w, h, dp = read_png(day)
pics = {'day': dp, 'dusk': read_png(dusk)[2], 'night': read_png(night)[2]}

leafy = lambda p: p[1] >= p[0] and p[1] > p[2] + 10
x0, y0, x1, y1 = TREE
for name, px in pics.items():
    rows = [[tuple(px[y][x][:3]) + (255,) if leafy(dp[y][x][:3]) else (0, 0, 0, 0) for x in range(x0, x1 + 1)] for y in range(y0, y1 + 1)]
    write_png(os.path.join(out, f'fishing-pond-phone-tree{"" if name == "day" else "-" + name}.png'), x1 - x0 + 1, y1 - y0 + 1, rows)


def is_water(p):
    r, g, b = p[:3]
    return b >= 0x60 and b > r + 40


passable = [[is_water(p) or min(p[:3]) > 0xC8 for p in row] for row in dp]
write_png(os.path.join(out, 'fishing-pond-phone-water.png'), w, h, [[(255, 255, 255, 255) if passable[y][x] else (0, 0, 0, 0) for x in range(w)] for y in range(h)])

pre = [[0] * (w + 1) for _ in range(h + 1)]
for y in range(h):
    for x in range(w):
        pre[y + 1][x + 1] = pre[y][x + 1] + pre[y + 1][x] - pre[y][x] + (0 if passable[y][x] else 1)
def solid_in(a, b, c, d):
    a, b, c, d = int(a), int(b), int(c), int(d)
    if a < 0 or b < 0 or c > w or d > h:
        return 1
    return pre[d][c] - pre[b][c] - pre[d][a] + pre[b][a]
GW, GH = round(w / R), round(h / R)
mask = []
for cy in range(GH // CELL):
    row = ''
    for cx in range(GW // CELL):
        gx, gy = cx * CELL + CELL / 2, cy * CELL + CELL / 2
        px, py = gx * R, gy * R
        row += '#' if solid_in(px - HALF_W * R, py - HALF_H * R, px + HALF_W * R + 1, py + HALF_H * R + 1) == 0 else '.'
    mask.append(row)
# the lake's lowest row: the last row where at least 10% of the middle is real water (white flowers and
# the light path below do not count)
lake_bottom = max((y for y in range(h) if sum(1 for x in range(60, 420) if is_water(dp[y][x])) >= 36), default=0)
lines = [
    '// Generated by tools/pixelize/pond_phone.py: the ducks\' water map for the phone pond (Ardian\'s',
    '// ChatGPT phone pictures), in the phone scene\'s grid (the picture / 1.4). \'#\' = only water under a',
    '// whole duck. Also the lowest water row (picture px), so the panel never covers the lake.',
    '',
    f'export const PHONE_WATER_CELL = {CELL};',
    f'export const PHONE_LAKE_BOTTOM_PX = {lake_bottom};',
    'export const PHONE_WATER_MASK: string[] = [',
] + [f"  '{r}'," for r in mask] + ['];']
open(out_ts, 'w').write('\n'.join(lines) + '\n')
print(f'phone pond: tree x3, water mask, duck map {len(mask[0])}x{len(mask)} (grid {GW}x{GH}), lake bottom row {lake_bottom}')
